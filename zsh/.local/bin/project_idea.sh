#!/usr/bin/env bash
# project-idea — capture and manage project ideas from a floating terminal.
set -euo pipefail

# ---------- Config ----------
PROJECTS_DIR="$HOME/Desktop/My_Projects/project_ideas"
INDEX_FILE="$PROJECTS_DIR/projects.md"
EDITOR="${EDITOR:-nvim}"

mkdir -p "$PROJECTS_DIR"
[ -f "$INDEX_FILE" ] || : >"$INDEX_FILE"

# ---------- Colors / helpers ----------
c_reset="\e[0m"
c_bold="\e[1m"
c_cyan="\e[36m"
c_green="\e[32m"
c_yellow="\e[33m"
c_red="\e[31m"

info() { printf "${c_cyan}==>${c_reset} %s\n" "$1"; }
ok() { printf "${c_green}✓${c_reset} %s\n" "$1"; }
warn() { printf "${c_yellow}!${c_reset} %s\n" "$1"; }
err() { printf "${c_red}✗${c_reset} %s\n" "$1" >&2; }

need() { command -v "$1" >/dev/null 2>&1 || {
  err "'$1' is required but not installed."
  exit 1
}; }

slugify() {
  echo "$1" | tr '[:upper:]' '[:lower:]' | sed -E 's/[^a-z0-9]+/-/g; s/^-+|-+$//g'
}

# Keep fzf compact-friendly for small floating terminals (niri, etc.)
fzf_height() {
  local rows
  rows=$(tput lines 2>/dev/null || echo 20)
  if [ "$rows" -lt 20 ]; then echo "95%"; else echo "70%"; fi
}

# Extract the body text under an exact "## <heading>" line, until the next "## " or EOF.
# Uses literal string matching (no regex) so headings with "()" etc. work fine.
extract_section() {
  local file="$1" heading="$2"
  awk -v h="## $heading" '
        BEGIN{found=0}
        index($0, h)==1 {found=1; next}
        /^## / {if(found) exit}
        found {print}
    ' "$file" | sed '/^[[:space:]]*$/d'
}

first_title() {
  grep -m1 '^# ' "$1" | sed 's/^# //'
}

# ---------- Index rebuild ----------
rebuild_index() {
  info "Rebuilding index..."
  {
    echo "# 📌 Project Ideas Index"
    echo
    echo "_Auto-generated by project-idea.sh — do not edit by hand._"
    echo
    echo "| Date | Project | Language(s) | Tech Stack |"
    echo "|------|---------|-------------|------------|"
  } >"$INDEX_FILE"

  shopt -s nullglob
  local files=("$PROJECTS_DIR"/*.md)
  shopt -u nullglob

  IFS=$'\n' files=($(printf '%s\n' "${files[@]}" | sort -r))
  unset IFS

  for f in "${files[@]}"; do
    [ "$(basename "$f")" = "projects.md" ] && continue
    local base date title lang stack
    base=$(basename "$f")
    date="${base:0:10}"
    title=$(first_title "$f")
    [ -z "$title" ] && title="$base"
    lang=$(extract_section "$f" "3. Programming Language(s) Planned to Use" | head -n1)
    stack=$(extract_section "$f" "4. Tech Stack Planned" | head -n1)
    [ -z "$lang" ] && lang="—"
    [ -z "$stack" ] && stack="—"
    printf "| %s | [%s](./%s) | %s | %s |\n" "$date" "$title" "$base" "$lang" "$stack" >>"$INDEX_FILE"
  done
  ok "Index updated -> $INDEX_FILE"
}

# ---------- New idea ----------
new_idea() {
  need "$EDITOR"
  printf "${c_bold}New project idea${c_reset}\n"
  read -rp "Title: " title
  [ -z "$title" ] && {
    err "Title cannot be empty."
    exit 1
  }

  local date slug fname path n
  date=$(date +%F)
  slug=$(slugify "$title")
  fname="${date}-${slug}.md"
  path="$PROJECTS_DIR/$fname"
  n=2
  while [ -e "$path" ]; do
    path="$PROJECTS_DIR/${date}-${slug}-${n}.md"
    n=$((n + 1))
  done

  cat >"$path" <<EOF
# $title

## 1. Project Base Idea


## 2. Project Idea in Detail



## 3. Programming Language(s) Planned to Use


## 4. Tech Stack Planned


## 5. Additional Notes

EOF

  "$EDITOR" "$path"

  # Discard if nothing meaningful was added beyond the empty template
  if ! grep -vqE '^(#{1,2}[^#].*|#|[[:space:]]*)$' "$path"; then
    warn "No content added — discarding empty idea."
    rm -f "$path"
    exit 0
  fi

  ok "Saved idea -> $path"
  rebuild_index
}

# ---------- fzf picker ----------
list_files() {
  shopt -s nullglob
  local files=("$PROJECTS_DIR"/*.md)
  shopt -u nullglob
  for f in "${files[@]}"; do
    [ "$(basename "$f")" = "projects.md" ] && continue
    basename "$f"
  done
}

pick_idea() {
  need fzf
  local list
  list=$(list_files)
  [ -z "$list" ] && {
    warn "No project ideas yet."
    exit 0
  }

  echo "$list" | sort -r | fzf \
    --height="$(fzf_height)" --layout=reverse --border=rounded \
    --prompt="Idea > " \
    --preview="bat --style=plain --color=always '$PROJECTS_DIR'/{} 2>/dev/null || cat '$PROJECTS_DIR'/{}" \
    --preview-window=right:60%:wrap
}

view_idea() {
  local sel
  sel=$(pick_idea) || exit 0
  [ -z "$sel" ] && exit 0
  if command -v bat >/dev/null 2>&1; then
    bat --style=plain --paging=always "$PROJECTS_DIR/$sel"
  else
    "${PAGER:-less}" "$PROJECTS_DIR/$sel"
  fi
}

edit_idea() {
  need "$EDITOR"
  local sel
  sel=$(pick_idea) || exit 0
  [ -z "$sel" ] && exit 0
  "$EDITOR" "$PROJECTS_DIR/$sel"
  rebuild_index
}

delete_idea() {
  need fzf
  local list
  list=$(list_files)
  [ -z "$list" ] && {
    warn "No project ideas yet."
    exit 0
  }

  local sels
  sels=$(echo "$list" | sort -r | fzf -m \
    --height="$(fzf_height)" --layout=reverse --border=rounded \
    --prompt="Delete (tab to multi-select) > " \
    --preview="bat --style=plain --color=always '$PROJECTS_DIR'/{} 2>/dev/null || cat '$PROJECTS_DIR'/{}" \
    --preview-window=right:60%:wrap)
  [ -z "$sels" ] && exit 0

  while IFS= read -r f; do
    rm -f "$PROJECTS_DIR/$f"
    ok "Deleted $f"
  done <<<"$sels"
  rebuild_index
}

open_index() { "$EDITOR" "$INDEX_FILE"; }

usage() {
  cat <<EOF
${c_bold}project-idea${c_reset} — capture and manage project ideas

Usage: project-idea [command]

Commands:
  (none), new     Create a new project idea (default)
  list, l         Browse ideas with fzf + preview
  edit, e         Pick an idea and edit it
  delete, d       Pick idea(s) to delete
  index, i        Open the auto-generated index
  rebuild         Force-rebuild the index
  help, -h        Show this help

Ideas are stored in: $PROJECTS_DIR
EOF
}

cmd="${1:-new}"
case "$cmd" in
new | n) new_idea ;;
list | l) view_idea ;;
edit | e) edit_idea ;;
delete | d) delete_idea ;;
index | i) open_index ;;
rebuild) rebuild_index ;;
help | -h | --help) usage ;;
*)
  err "Unknown command: $cmd"
  usage
  exit 1
  ;;
esac
